const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const root = path.resolve(__dirname, '..');
const app = process.env.DOT_MD_APP_PATH || path.join(root, 'dist', 'md any where.app');
const extension = path.join(app, 'Contents', 'PlugIns', 'DOTMDQuickLook.appex');
const thumbnailExtension = path.join(app, 'Contents', 'PlugIns', 'DOTMDThumbnail.appex');
const info = path.join(extension, 'Contents', 'Info.plist');
const executable = path.join(extension, 'Contents', 'MacOS', 'DOTMDQuickLook');
const previewSource = fs.readFileSync(path.join(root, 'Sources', 'DOTMDQuickLook', 'PreviewProvider.swift'), 'utf8');
assert.ok(fs.existsSync(info), 'Quick Look extension Info.plist must be bundled');
assert.ok(fs.existsSync(executable), 'Quick Look extension executable must be bundled');
assert.ok(fs.existsSync(path.join(thumbnailExtension, 'Contents', 'MacOS', 'DOTMDThumbnail')), 'Finder thumbnail extension executable must be bundled');
const plist = spawnSync('/usr/libexec/PlistBuddy', ['-c', 'Print :NSExtension:NSExtensionPointIdentifier', info], {encoding:'utf8'});
assert.equal(plist.stdout.trim(), 'com.apple.quicklook.preview');
const types = spawnSync('/usr/libexec/PlistBuddy', ['-c', 'Print :NSExtension:NSExtensionAttributes:QLSupportedContentTypes:0', info], {encoding:'utf8'});
assert.equal(types.stdout.trim(), 'net.daringfireball.markdown');
const principal = spawnSync('/usr/libexec/PlistBuddy', ['-c', 'Print :NSExtension:NSExtensionPrincipalClass', info], {encoding:'utf8'});
assert.equal(principal.stdout.trim(), 'DOTMDQuickLook.PreviewViewController');
const dataBased = spawnSync('/usr/libexec/PlistBuddy', ['-c', 'Print :NSExtension:NSExtensionAttributes:QLIsDataBasedPreview', info], {encoding:'utf8'});
assert.equal(dataBased.stdout.trim(), 'false');
assert.match(previewSource, /NSTextView/, 'Quick Look must use native text rendering');
assert.doesNotMatch(previewSource, /WKWebView|loadHTMLString/, 'Quick Look must not require a sandboxed WebKit child process');
const thumbnailInfo = path.join(thumbnailExtension, 'Contents', 'Info.plist');
const thumbnailPoint = spawnSync('/usr/libexec/PlistBuddy', ['-c', 'Print :NSExtension:NSExtensionPointIdentifier', thumbnailInfo], {encoding:'utf8'});
assert.equal(thumbnailPoint.stdout.trim(), 'com.apple.quicklook.thumbnail');
const signature = spawnSync('codesign', ['--verify', '--deep', '--strict', app], {encoding:'utf8'});
assert.equal(signature.status, 0, signature.stderr);
console.log('Bundled sandboxed Markdown Quick Look extension passed.');
